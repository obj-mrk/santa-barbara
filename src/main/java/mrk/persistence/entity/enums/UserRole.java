package mrk.persistence.entity.enums;
/**
 * Перечисление ролей пользователя в системе
 * Определяет уровень доступа и права пользователей
 */
public enum UserRole {
    /**
     * Обычный зарегистрированный пользователь
     * Имеет базовые права на использование системы
     */
    USER,

    /**
     * Администратор системы
     * Имеет полный доступ ко всем функциям и данным
     */
    ADMIN,

    /**
     * Временный пользователь с ограниченными правами
     */
    GUEST
}
